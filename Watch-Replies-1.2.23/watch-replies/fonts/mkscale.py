"""Makes the small name font N (Latin only) by scaling the 27 px Noto Sans Medium glyphs of src/fonts.rs by 7/9 (21 px).
Usage: python3 fonts/mkscale.py   (writes src/fonts_small.rs; Noto Sans is SIL OFL 1.1)"""
import re
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
src = (ROOT / "src" / "fonts.rs").read_text(encoding="utf-8")
b = src[src.index("pub static B: Font"):]
head = re.search(r"ascent: (\d+), descent: (\d+), cap: (\d+)", b)
asc, desc, cap = map(int, head.groups())
glyph_part = b[b.index("glyphs: &["):b.index("    ],\n    bits:")]
bits_part = b[b.index("    bits: &["):b.index("    ],\n    arabic_ascent")]
bits = [int(x) for x in re.findall(r"\d+", bits_part[bits_part.index("["):])]
rows = re.findall(r"Glyph \{ c: '(.*?)', adv: (\d+), x: (-?\d+), y: (-?\d+), w: (\d+), h: (\d+), off: (\d+) \}", glyph_part)
N, D, PAD, UP, DOWN = 7, 9, 9, 36, 18
out_rows, data = [], bytearray()
for ch, adv, x, y, w, h, off in rows:
    adv, x, y, w, h, off = map(int, (adv, x, y, w, h, off))
    cw = -(-(adv + 2 * PAD + w) // D) * D
    ch_ = UP + DOWN
    canvas = Image.new("L", (cw, ch_), 0)
    if w and h:
        for i in range(w * h):
            v = (bits[off + i // 4] >> (6 - 2 * (i % 4))) & 3
            if v:
                canvas.putpixel((PAD + x + i % w, UP + y + i // w), v * 85)
    small = canvas.resize((cw * N // D, ch_ * N // D), Image.BOX)
    q = small.point(lambda v: (v * 15 + 127) // 255 * 17)
    box = q.getbbox()
    x0 = y0 = ww = hh = 0
    o = len(data)
    if box:
        x0, y0 = box[0] - PAD * N // D, box[1] - UP * N // D
        ww, hh = box[2] - box[0], box[3] - box[1]
        px = [min(3, ((v // 17) + 2) // 5) for v in q.crop(box).get_flattened_data()]
        px.extend([0] * ((-len(px)) % 4))
        data.extend((px[i] << 6) | (px[i + 1] << 4) | (px[i + 2] << 2) | px[i + 3] for i in range(0, len(px), 4))
    out_rows.append((ch, round(adv * N / D), x0, y0, ww, hh, o))
lines = ["//! Generated by fonts/mkscale.py from the 27 px Noto Sans Medium glyphs (SIL OFL 1.1). Do not edit.", "",
         "use crate::font::{Font, Glyph};", "",
         "/// Noto Sans Medium at 21 px, Latin only: the sender's name in a bubble.",
         "pub static N: Font = Font {",
         f"    ascent: {round(asc*N/D)}, descent: {round(desc*N/D)}, cap: {round(cap*N/D)},", "    glyphs: &["]
for ch, adv, x, y, w, h, o in out_rows:
    lines.append(f"        Glyph {{ c: '{ch}', adv: {adv}, x: {x}, y: {y}, w: {w}, h: {h}, off: {o} }},")
lines += ["    ],", "    bits: &["]
for i in range(0, len(data), 24):
    lines.append("        " + " ".join(f"{v}," for v in data[i:i + 24]))
lines += ["    ],", "    arabic_ascent: 0, arabic_descent: 0, arabic_cap: 0,", "    arabic_glyphs: &[],", "    arabic_bits: &[],", "};", ""]
(ROOT / "src" / "fonts_small.rs").write_text("\n".join(lines), encoding="utf-8")
print(len(out_rows), "glyphs", len(data), "bytes")
