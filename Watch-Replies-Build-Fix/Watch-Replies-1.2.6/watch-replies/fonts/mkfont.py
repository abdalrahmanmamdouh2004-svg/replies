"""Generate compact anti-aliased English and Arabic glyph tables for Watch Replies.

Usage:
  uv run --with pillow python fonts/mkfont.py [directory containing Noto fonts]

Expected files: NotoSans-SemiBold.ttf, NotoSans-Medium.ttf,
NotoSansArabic-SemiBold.ttf, NotoSansArabic-Medium.ttf.
"""
import re
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parent / "ttf")
OUT = Path(__file__).resolve().parent.parent / "src" / "fonts.rs"
ASCII = "".join(chr(c) for c in range(32, 127)) + "…·"

# Only forms referenced by the shaper are embedded. Including the entire
# presentation-form block also rasterised dozens of unused/tofu glyphs.
SHAPER = Path(__file__).resolve().parent.parent / "src" / "arabic.rs"
SHAPE_FORMS = {int(cp, 16) for cp in re.findall(r"\\u\{([0-9A-Fa-f]+)\}", SHAPER.read_text(encoding="utf-8"))
               if 0xFE70 <= int(cp, 16) <= 0xFEFF}
ARABIC_EXTRA = SHAPE_FORMS | {0x0640, 0x060C, 0x061B, 0x061F}
ARABIC_EXTRA |= set(range(0x0660, 0x066A)) | set(range(0x06F0, 0x06FA))
ARABIC = "".join(chr(cp) for cp in sorted(ARABIC_EXTRA))


def rust_char(ch):
    cp = ord(ch)
    if ch == "'": return "\\'"
    if ch == "\\": return "\\\\"
    if cp < 0x20 or cp > 0x7E: return f"\\u{{{cp:04X}}}"
    return ch


def glyphs(path, px, chars):
    font = ImageFont.truetype(str(path), px)
    ascent, descent = font.getmetrics()
    rows, data = [], bytearray()
    seen = set()
    for ch in chars:
        if ch in seen: continue
        seen.add(ch)
        adv = max(0, round(font.getlength(ch)))
        big = Image.new("L", (px * 3, px * 3), 0)
        ImageDraw.Draw(big).text((px, px * 2), ch, font=font, fill=255, anchor="ls")
        q = big.point(lambda v: (v * 15 + 127) // 255 * 17)
        box = q.getbbox()
        x0 = y0 = w = h = 0
        off = len(data)
        if box:
            x0, y0 = box[0] - px, box[1] - px * 2
            w, h = box[2] - box[0], box[3] - box[1]
            # Quantise 16-bit coverage to four levels and pack four pixels per byte.
            # The renderer expands each 2-bit level to one of 16 preblended colours.
            px2 = [min(3, ((v // 17) + 2) // 5) for v in q.crop(box).get_flattened_data()]
            px2.extend([0] * ((-len(px2)) % 4))
            data.extend((px2[i] << 6) | (px2[i + 1] << 4) | (px2[i + 2] << 2) | px2[i + 3]
                        for i in range(0, len(px2), 4))
        rows.append((ch, min(255, adv), x0, y0, w, h, off))
    cap = font.getbbox("H", anchor="ls")[1]
    if len(data) > 65535:
        raise SystemExit(f"{path.name} glyph bitmap too large for u16 offsets: {len(data)} bytes")
    return ascent, descent, -cap, rows, data


def emit_font(out, name, latin_file, arabic_file, px, arabic_px):
    ascent, descent, cap, rows, data = glyphs(SRC / latin_file, px, ASCII)
    aa, ad, ac, arows, adata = glyphs(SRC / arabic_file, arabic_px, ARABIC)
    out.append(f"/// {latin_file[:-4]} at {px}px plus {arabic_file[:-4]} at {arabic_px}px.")
    out.append(f"pub static {name}: Font = Font {{")
    out.append(f"    ascent: {ascent}, descent: {descent}, cap: {cap},")
    out.append("    glyphs: &[")
    for ch, adv, x, y, w, h, off in rows:
        out.append(f"        Glyph {{ c: '{rust_char(ch)}', adv: {adv}, x: {x}, y: {y}, w: {w}, h: {h}, off: {off} }},")
    out.append("    ],")
    out.append("    bits: &[")
    for i in range(0, len(data), 24): out.append("        " + " ".join(f"{b}," for b in data[i:i + 24]))
    out.append("    ],")
    out.append(f"    arabic_ascent: {aa}, arabic_descent: {ad}, arabic_cap: {ac},")
    out.append("    arabic_glyphs: &[")
    for ch, adv, x, y, w, h, off in arows:
        out.append(f"        Glyph {{ c: '{rust_char(ch)}', adv: {adv}, x: {x}, y: {y}, w: {w}, h: {h}, off: {off} }},")
    out.append("    ],")
    out.append("    arabic_bits: &[")
    for i in range(0, len(adata), 24): out.append("        " + " ".join(f"{b}," for b in adata[i:i + 24]))
    out.append("    ],")
    out.append("};\n")
    print(f"{name}: latin {len(rows)} glyphs / {len(data)} B, Arabic {len(arows)} glyphs / {len(adata)} B")


def main():
    out = [
        "//! Generated by fonts/mkfont.py from Noto Sans and Noto Sans Arabic (SIL OFL 1.1). Do not edit.",
        "",
        "use crate::font::{Font, Glyph};",
        "",
    ]
    emit_font(out, "T", "NotoSans-SemiBold.ttf", "NotoSansArabic-SemiBold.ttf", 32, 32)
    emit_font(out, "B", "NotoSans-Medium.ttf", "NotoSansArabic-Medium.ttf", 27, 27)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUT} ({OUT.stat().st_size} bytes)")

if __name__ == "__main__": main()
